export type Lang = "tr" | "en";

const dictionaries: Record<Lang, Record<Key, string>> = { tr, en };
const listeners = new Set<() => void>();
// English by default; Turkish when the person chose it.
let current: Lang = readLocal("lang") === "tr" ? "tr" : "en";
// Uppercase labels follow the page language (Turkish turns i into İ).
document.documentElement.lang = current;

function setLang(lang: Lang) {
  current = lang;
  writeLocal("lang", lang);
  document.documentElement.lang = lang;
  listeners.forEach((l) => l());
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

export function useT() {
  const lang = useSyncExternalStore(subscribe, () => current);
  const t = (key: Key) => dictionaries[lang][key];
  return { t, lang, setLang };
}
